export function BookmarkButton({ id, label = true }: { id: string; label?: boolean }) {
  const on = useStore((s) => s.bookmarks.includes(id));
  const I = on ? BookmarkCheck : Bookmark;
  return (
    <button className={`btn btn-sm ${on ? 'btn-primary' : ''}`} onClick={() => store.toggleBookmark(id)} aria-pressed={on} title={on ? 'Remove bookmark' : 'Bookmark'}>
      <I className="h-3.5 w-3.5" />{label && (on ? 'Saved' : 'Save')}
    </button>
  );
}

export function PageHeader({ eyebrow, title, children, actions }: { eyebrow?: string; title: string; children?: ReactNode; actions?: ReactNode }) {
  return (
    <div className="mb-6 flex flex-col gap-3 md:flex-row md:items-end md:justify-between">
      <div className="max-w-3xl">
        {eyebrow && <div className="mb-1 text-xs font-semibold uppercase tracking-[0.14em] text-cyan-400">{eyebrow}</div>}
        <h1 className="h1">{title}</h1>
        {children && <div className="mt-2 text-[15px] leading-relaxed text-slate-400">{children}</div>}
      </div>
      {actions && <div className="flex shrink-0 flex-wrap gap-2">{actions}</div>}
    </div>
  );
}

export function Tabs<T extends string>({ value, onChange, options, size = 'md' }: { value: T; onChange: (v: T) => void; options: { id: T; label: string }[]; size?: 'sm' | 'md' }) {
  return (
    <div role="tablist" className="inline-flex rounded-lg border border-ink-600 bg-ink-950 p-0.5">
      {options.map((o) => (
        <button key={o.id} role="tab" aria-selected={value === o.id} onClick={() => onChange(o.id)}
          className={`rounded-md font-medium transition ${size === 'sm' ? 'px-2 py-0.5 text-xs' : 'px-3 py-1 text-sm'} ${value === o.id ? 'bg-ink-700 text-white' : 'text-slate-400 hover:text-slate-200'}`}>
          {o.label}
        </button>
      ))}
    </div>
  );
}

